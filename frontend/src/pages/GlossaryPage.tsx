export default function GlossaryPage() {
  const [searchTerm, setSearchTerm] = useState('')

  // Фильтрация терминов
  const filteredGlossary = Object.entries(glossaryData).reduce((acc, [letter, terms]) => {
    const filteredTerms = terms.filter(
      (item) =>
        item.term.toLowerCase().includes(searchTerm.toLowerCase()) ||
        item.definition.toLowerCase().includes(searchTerm.toLowerCase())
    )
    if (filteredTerms.length > 0) {
      acc[letter] = filteredTerms
    }
    return acc
  }, {} as typeof glossaryData)

  const totalTerms = Object.values(glossaryData).flat().length

  return (
    <Container maxWidth="lg" sx={{ py: { xs: 4, sm: 6 } }}>
      {/* Заголовок с поиском */}
      <Box sx={{ mb: 4 }}>
        <Typography variant="h4" sx={{ mb: 2, fontWeight: 700 }}>
          📖 Словарь инвестора
        </Typography>
        <Typography variant="body1" color="text.secondary" sx={{ mb: 3 }}>
          {totalTerms} терминов и определений для помощи в обучении
        </Typography>

        <TextField
          fullWidth
          placeholder="Поиск термина..."
          value={searchTerm}
          onChange={(e) => setSearchTerm(e.target.value)}
          InputProps={{
            startAdornment: (
              <InputAdornment position="start">
                <SearchIcon color="action" />
              </InputAdornment>
            ),
          }}
          sx={{ mb: 3 }}
        />

        {/* Кот-помощник */}
        <Paper
          sx={{
            p: 2,
            bgcolor: 'rgba(255, 152, 0, 0.08)',
            borderRadius: 2,
            display: 'flex',
            alignItems: 'center',
            gap: 2,
          }}
        >
          <Box
            component="img"
            src="https://media.giphy.com/media/MDJ9IbxxvDUQM/giphy.gif"
            alt="Кот-помощник"
            sx={{ width: 80, height: 80, borderRadius: 2, objectFit: 'cover' }}
          />
          <Box>
            <Box sx={{ display: 'flex', alignItems: 'center', gap: 1, mb: 1 }}>
              <AutoAwesomeIcon color="warning" />
              <Typography variant="subtitle2" sx={{ fontWeight: 700 }}>
                Кот-Инвестор:
              </Typography>
            </Box>
            <Typography variant="body2" sx={{ fontStyle: 'italic' }}>
              🎓 Запомни: не обязательно знать все термины наизусть! Главное — понимать суть и уметь применять знания на практике. Возвращайся к словарю когда нужно!
            </Typography>
          </Box>
        </Paper>
      </Box>

      {/* Список терминов по буквам */}
      {Object.entries(filteredGlossary).map(([letter, terms]) => (
        <Box key={letter} sx={{ mb: 4 }}>
          <Box
            sx={{
              display: 'flex',
              alignItems: 'center',
              gap: 2,
              mb: 2,
            }}
          >
            <Chip
              label={letter}
              size="medium"
              sx={{
                bgcolor: 'primary.main',
                color: 'primary.contrastText',
                fontWeight: 700,
                width: 40,
                height: 40,
              }}
            />
            <Divider sx={{ flex: 1 }} />
          </Box>

          <Grid container spacing={2}>
            {terms.map((item, index) => (
              <Grid item xs={12} key={index}>
                <Paper
                  sx={{
                    p: 2.5,
                    bgcolor: 'rgba(255,255,255,0.03)',
                    borderRadius: 2,
                    transition: 'all 0.2s',
                    '&:hover': {
                      bgcolor: 'rgba(255,255,255,0.06)',
                      transform: 'translateX(4px)',
                    },
                  }}
                >
                  <Typography variant="h6" sx={{ fontWeight: 700, mb: 1, color: 'primary.main' }}>
                    {item.term}
                  </Typography>
                  <Typography variant="body2" color="text.secondary" sx={{ mb: 1, lineHeight: 1.7 }}>
                    {item.definition}
                  </Typography>
                  {item.example && (
                    <Typography
                      variant="body2"
                      sx={{
                        mt: 1,
                        pt: 1,
                        borderTop: '1px solid rgba(255,255,255,0.1)',
                        color: 'text.secondary',
                        fontStyle: 'italic',
                        fontSize: '0.9rem',
                      }}
                    >
                      💡 {item.example}
                    </Typography>
                  )}
                </Paper>
              </Grid>
            ))}
          </Grid>
        </Box>
      ))}

      {Object.keys(filteredGlossary).length === 0 && (
        <Paper sx={{ p: 6, textAlign: 'center' }}>
          <Typography variant="h6" color="text.secondary">
            🔍 Ничего не найдено по запросу "{searchTerm}"
          </Typography>
          <Typography variant="body2" color="text.secondary" sx={{ mt: 1 }}>
            Попробуйте изменить поисковый запрос
          </Typography>
        </Paper>
      )}
    </Container>
  )
}
