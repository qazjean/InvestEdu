        ('2005-01-01', '2006-01-01', 13.0),
        ('2006-01-01', '2007-01-01', 11.0),
        ('2007-01-01', '2008-01-01', 10.25),
        ('2008-01-01', '2008-09-01', 10.75),
        ('2008-09-01', '2008-12-01', 13.0),
        ('2008-12-01', '2009-06-01', 11.0),
        ('2009-06-01', '2010-01-01', 8.25),
        ('2010-01-01', '2011-01-01', 8.0),
        ('2011-01-01', '2012-01-01', 8.0),
        ('2012-01-01', '2013-01-01', 8.25),
        ('2013-01-01', '2014-01-01', 8.25),
        ('2014-01-01', '2014-12-01', 17.0),
        ('2014-12-01', '2015-06-01', 11.5),
        ('2015-06-01', '2016-01-01', 11.0),
