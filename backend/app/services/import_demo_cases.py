def import_cases():
    db = SessionLocal()
    try:
        existing_count = db.query(Case).count()
        if existing_count > 0:
            print(f"⚠️  В БД уже есть {existing_count} кейсов. Удаляем...")
            db.query(Case).delete()
            db.commit()
        
        for case_id, case_data in ENRICHED_CASES.items():
            case = Case(
                id=case_id,
                title=case_data['title'],
                description=case_data['description'],
                difficulty=case_data['difficulty'],
                category=case_data['category'],
                year=case_data['year'],
                scenario_data=case_data['scenario_data'],
                correct_decision=case_data['correct_decision'],
                explanation=case_data['explanation'],
                points=case_data['points']
            )
            db.add(case)
            print(f"✅ Добавлен: {case.title}")
        
        db.commit()
        print(f"\n🎉 Импортировано {len(ENRICHED_CASES)} кейсов с ПОЛНЫМИ данными")
        return True
        
    except Exception as e:
        db.rollback()
        print(f"❌ Ошибка: {e}")
        import traceback
        traceback.print_exc()
        return False
    finally:
        db.close()


if __name__ == "__main__":
    import_cases()
