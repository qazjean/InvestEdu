def import_cases():
    if not CASES_FILE.exists():
        print(f"❌ {CASES_FILE} не найден")
        return False
    
    with open(CASES_FILE, 'r', encoding='utf-8') as f:
        cases_data = json.load(f)
    
    db = SessionLocal()
    try:
        existing_count = db.query(Case).count()
        if existing_count > 0:
            print(f"⚠️  В БД уже есть {existing_count} кейсов. Удаляем...")
            db.query(Case).delete()
            db.commit()
        
        for case_data in cases_data:
            period = case_data.get('period', {})
            
            # Добавляем обогащённые данные
            case_id = case_data['id']
            enriched = ENRICHED_CASES.get(case_id, {})
            
            # Обновляем scenario_data с дополнительной информацией
            scenario_data = case_data.get('scenario_data', {})
            if enriched:
                scenario_data['full_description'] = enriched.get('full_description', '')
                scenario_data['learning_points'] = enriched.get('learning_points', [])
            
            case = Case(
                id=case_id,
                title=case_data['title'],
                description=period.get('description', case_data.get('context', {}).get('key_question', '')),
                difficulty=case_data.get('difficulty', 'medium'),
                category=case_data.get('category', 'fundamental'),
                year=int(period.get('start', '2018')[:4]),
                scenario_data=scenario_data,
                correct_decision=case_data.get('correct_decision', {}).get('primary', 'hold'),
                explanation=case_data.get('correct_decision', {}).get('explanation', ''),
                points=case_data.get('points', {}).get('correct_decision', 50)
            )
            db.add(case)
            print(f"✅ Добавлен: {case.title}")
        
        db.commit()
        print(f"\n🎉 Импортировано {len(cases_data)} кейсов (с обогащёнными данными)")
        return True
        
    except Exception as e:
        db.rollback()
        print(f"❌ Ошибка: {e}")
        return False
    finally:
        db.close()


if __name__ == "__main__":
    import_cases()
