def init_deep_db():
    """Инициализация БД с глубоким контентом"""
    db = Session(bind=engine)
    
    try:
        # Проверяем существующие данные
        existing = db.query(Lesson).filter(Lesson.module_id == 1).count()
        if existing > 0:
            print(f"⚠️ Модуль 1 уже существует ({existing} уроков). Удаляем...")
            db.query(Lesson).filter(Lesson.module_id == 1).delete()
            db.commit()
        
        lessons = get_deep_lessons_module1()
        
        for l in lessons:
            lesson = Lesson(**l)
            db.add(lesson)
            print(f"  Добавлен урок: {l['title']}")
        
        db.commit()
        
        print(f"\n✅ Модуль 1 инициализирован: {len(lessons)} уроков")
        
    except Exception as e:
        db.rollback()
        print(f"❌ Ошибка: {e}")
        raise
    finally:
        db.close()


if __name__ == "__main__":
    init_deep_db()
