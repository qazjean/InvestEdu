def init_db():
    """Инициализация БД с данными"""
    db = Session(bind=engine)
    
    try:
        # Проверяем, есть ли уже данные
        existing_modules = db.query(Module).count()
        if existing_modules > 0:
            print("База данных уже инициализирована!")
            return
        
        # Создаём модули
        modules_data = get_modules_data()
        for m in modules_data:
            module = Module(**m)
            db.add(module)
        db.commit()
        
        # Создаём уроки
        lessons_data = get_lessons_data()
        for l in lessons_data:
            lesson = Lesson(**l)
            db.add(lesson)
        db.commit()
        
        # Создаём кейсы
        cases_data = get_cases_data()
        for c in cases_data:
            case = Case(**c)
            db.add(case)
        db.commit()
        
        print("✅ База данных успешно инициализирована!")
        print(f"   - Модулей: {len(modules_data)}")
        print(f"   - Уроков: {len(lessons_data)}")
        print(f"   - Кейсов: {len(cases_data)}")
        
    except Exception as e:
        db.rollback()
        print(f"❌ Ошибка инициализации: {e}")
        raise
    finally:
        db.close()


if __name__ == "__main__":
    init_db()
